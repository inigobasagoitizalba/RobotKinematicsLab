package com.robotkinematicslab.mobile.diagnostics.benchmark.generation

import com.robotkinematicslab.mobile.diagnostics.benchmark.result.DiagnosticExpectedClass

import com.robotkinematicslab.mobile.domain.RobotDefinition
import com.robotkinematicslab.mobile.domain.RobotState
import com.robotkinematicslab.mobile.domain.result.FKStatus
import com.robotkinematicslab.mobile.math.utility.Vec3
import com.robotkinematicslab.mobile.reproducibility.ScientificRandom
import com.robotkinematicslab.mobile.service.KinematicsService
import kotlin.math.PI
import kotlin.math.abs
import kotlin.math.cos
import kotlin.math.sin

class DiagnosticTargetFactory {

    fun buildTargetCases(
        kinematicsService: KinematicsService,
        robot: RobotDefinition,
        reachableCount: Int,
        unreachableCount: Int,
        random: ScientificRandom,
        maxReach: Double
    ): List<DiagnosticTargetCase> {
        val cases = mutableListOf<DiagnosticTargetCase>()

        cases += buildFkProvenReachableCases(
            kinematicsService = kinematicsService,
            robot = robot,
            reachableCount = reachableCount,
            random = random
        )

        repeat(unreachableCount) { index ->
            val nearBoundary = random.nextInt(2) == 0
            cases += DiagnosticTargetCase(
                id = "U${index + 1}",
                expectedClass = DiagnosticExpectedClass.UNREACHABLE,
                target = randomUnreachableTarget(
                    random = random,
                    maxReach = maxReach,
                    nearBoundary = nearBoundary
                ),
                sourceJointState = null,
                note =
                    if (nearBoundary) {
                        "Hard negative generated 1-10% outside a proven conservative radial reach bound."
                    } else {
                        "Far negative generated 15-70% outside a proven conservative radial reach bound."
                    }
            )
        }

        return cases
    }

    private fun buildFkProvenReachableCases(
        kinematicsService: KinematicsService,
        robot: RobotDefinition,
        reachableCount: Int,
        random: ScientificRandom
    ): List<DiagnosticTargetCase> {
        val cases = mutableListOf<DiagnosticTargetCase>()

        var attempts = 0
        val maxAttempts = (reachableCount * 50).coerceAtLeast(100)

        while (cases.size < reachableCount && attempts < maxAttempts) {
            attempts += 1

            val sourceState = randomRobotState(
                robot = robot,
                random = random
            )

            val fkResult = kinematicsService.computeFK(
                robot = robot,
                state = sourceState
            )

            val fkAccepted = fkResult.status == FKStatus.SUCCESS ||
                    fkResult.status == FKStatus.SUCCESS_WITH_WARNING

            if (!fkAccepted) {
                continue
            }

            val target = fkResult.endEffectorPosition

            val duplicate = cases.any { existing ->
                squaredDistance(existing.target, target) < 1e-8
            }

            if (duplicate) {
                continue
            }

            cases += DiagnosticTargetCase(
                id = "R${cases.size + 1}",
                expectedClass = DiagnosticExpectedClass.REACHABLE,
                target = target,
                sourceJointState = sourceState,
                note = "Reachable target generated by FK from a valid random joint state. This is FK-proven reachable."
            )
        }

        return cases
    }

    private fun randomRobotState(
        robot: RobotDefinition,
        random: ScientificRandom
    ): RobotState {
        val jointValues = robot.joints.map { joint ->
            random.nextDouble(
                from = joint.minValue,
                until = joint.maxValue
            )
        }

        return RobotState(jointValues)
    }

    private fun randomUnreachableTarget(
        random: ScientificRandom,
        maxReach: Double,
        nearBoundary: Boolean
    ): Vec3 {
        require(maxReach.isFinite() && maxReach > 0.0) {
            "A finite positive conservative reach bound is required."
        }
        val lowerFactor = if (nearBoundary) 1.01 else 1.15
        val upperFactor = if (nearBoundary) 1.10 else 1.70
        val radius = random.nextDouble(
            maxReach * lowerFactor,
            maxReach * upperFactor
        )

        val angle = random.nextDouble(
            -PI,
            PI
        )

        val x = radius * cos(angle)
        val z = abs(radius * sin(angle))

        return Vec3(
            x = x,
            y = 0.0,
            z = z
        )
    }

    private fun squaredDistance(
        a: Vec3,
        b: Vec3
    ): Double {
        val dx = a.x - b.x
        val dy = a.y - b.y
        val dz = a.z - b.z
        return dx * dx + dy * dy + dz * dz
    }
}
